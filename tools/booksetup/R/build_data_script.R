#' Build an R script that generates all book temp data
#'
#' Writes a short R script that, when sourced in a session where booksetup is
#' loaded, calls [generate_book_data()] with the specified parameters. This is
#' a convenience for workflows that prefer an explicit script file; for direct
#' use from R, call [generate_book_data()] instead.
#'
#' @param book_dir Path to the book project root (must contain `_quarto.yml`).
#' @param output Path for the generated R script. Defaults to a timestamped
#'   file under `tempdir/` in the current working directory.
#' @param chapters Optional character vector of chapter names (without `.qmd`)
#'   to limit the generation. If `NULL` (the default), all chapters are included.
#' @param exclude Optional character vector of chapter names to exclude.
#'   Unknown names are ignored with a warning.
#' @param registry Path to the YAML chunk-completion registry. Defaults to
#'   [registry_path()].
#' @param python_sync If `TRUE`, rsync R data to the Python temp directory.
#' @param image_dir Directory where chunk plots are saved as PNG files.
#'   Defaults to `generated_images/` next to the registry file.
#' @param image_width,image_height,image_res Pixel width/height and resolution
#'   (dpi) for saved chunk plots.
#'
#' @return The path to the generated R script, invisibly.
#'
#' @export
#'
#' @examples
#' \dontrun{
#' build_data_script("/home/rolf/gh/sitsbook", "generate_book_data.R")
#' }
build_data_script <- function(book_dir,
                              output = file.path(
                                "tempdir",
                                paste0("generate_book_data_",
                                       format(Sys.time(), "%Y%m%d_%H%M%S"),
                                       ".R")
                              ),
                              chapters = NULL,
                              exclude = NULL,
                              registry = registry_path(),
                              python_sync = TRUE,
                              image_dir = file.path(
                                dirname(registry %||% registry_path()),
                                "generated_images"
                              ),
                              image_width = 2000L,
                              image_height = 1500L,
                              image_res = 150L) {
  # Validate chapters/exclude early
  resolve_chapters(book_dir, chapters, exclude)

  out_path <- normalizePath(output, winslash = "/", mustWork = FALSE)
  out_dir <- dirname(out_path)
  if (!dir.exists(out_dir)) {
    dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
  }

  log_file <- sub("\\.R$", ".log", out_path)

  lines <- c(
    "# Generated by booksetup::build_data_script()",
    "# Do not edit by hand.",
    "#",
    "# This script calls booksetup::generate_book_data() directly.",
    "# Run it in an R session where booksetup is loaded:",
    "#   pkgload::load_all('tools/booksetup')",
    "#   source('this_script.R')",
    "",
    sprintf("booksetup::generate_book_data("),
    sprintf("  book_dir = %s,", deparse(normalizePath(book_dir, winslash = "/"))),
    sprintf("  chapters = %s,", deparse(chapters)),
    sprintf("  exclude = %s,", deparse(exclude)),
    sprintf("  registry = %s,",
            deparse(normalizePath(registry %||% registry_path(),
                                  winslash = "/", mustWork = FALSE))),
    sprintf("  python_sync = %s,", deparse(python_sync)),
    sprintf("  image_dir = %s,",
            deparse(normalizePath(image_dir, winslash = "/", mustWork = FALSE))),
    sprintf("  image_width = %s,", deparse(image_width)),
    sprintf("  image_height = %s,", deparse(image_height)),
    sprintf("  image_res = %s,", deparse(image_res)),
    sprintf("  log_file = %s", deparse(log_file)),
    ")"
  )

  writeLines(lines, out_path)
  invisible(out_path)
}
